describe("proseDashLines: a dash at the end of a line", () => {
  it("counts it, since the sentence continues on the next line", () => {
    expect(proseDashLines("a.md", "First part --\nsecond part.")).toEqual([1])
    expect(proseDashLines("a.ts", "// heading --\n// more")).toEqual([1])
    expect(proseDashLines("ci.yml", "# done --")).toEqual([1])
  })
})

describe("proseDashLines: comments after templates and regular expressions", () => {
  it("keeps reading comments after a template substitution, a regex and JSX", () => {
    const ts = [
      "const a = `x${1}y`",
      "// a -- b",
      "const r = /a\\/-- b/",
      "// c -- d",
      "const t = `${`n${2}`}`",
      "/* e -- f */",
    ].join("\n")
    expect(proseDashLines("a.ts", ts)).toEqual([2, 4, 6])
    expect(proseDashLines("a.mjs", "const a = `${x}`\n// g -- h")).toEqual([2])
    expect(proseDashLines("a.tsx", "const v = <div>{`${x}`}</div>\n// i -- j")).toEqual([2])
  })
})

describe("commentRanges", () => {
  it("finds each comment once, in order, including one before a closing brace and at the end of the file", () => {
    const text = "/** a */\nfunction f() {\n  // b\n  return 1 // c\n  /* d */\n}\n// e"
    const bodies = commentRanges("x.ts", text).map(([s, e]) => text.slice(s, e))
    expect(bodies).toEqual(["/** a */", "// b", "// c", "/* d */", "// e"])
  })
  it("parses JSX in .tsx, .jsx and JavaScript files, where // inside an element is text", () => {
    const text = "const v = <div>a // b</div>"
    for (const file of ["Card.tsx", "Card.jsx", "a.js", "a.mjs", "a.cjs"])
      expect(commentRanges(file, text), file).toEqual([])
  })
  it("parses TypeScript by the final extension, where // after a type assertion is a comment", () => {
    const text = "const v = <div>a // b</div>"
    for (const file of ["a.ts", "Card.tsx.ts", "a.js.ts"])
      expect(commentRanges(file, text), file).toEqual([[17, 27]])
  })
})

describe("proseDashLines: comments beside punctuation and wrapped spans", () => {
  it("reads a comment after a comma and before a closing bracket", () => {
    const text = [
      "const o = {",
      "  a: 1, // x -- y",
      "  b: [2, // p -- q",
      "  ], // r -- s",
      "}",
    ].join("\n")
    expect(proseDashLines("a.ts", text)).toEqual([2, 3, 4])
  })
  it("treats a code span that wraps across two // lines as code, and still reads the prose around it", () => {
    const text = ["// run `npm run x", "// -- --flag` first, then -- stop."].join("\n")
    expect(proseDashLines("a.ts", text)).toEqual([2])
    const quiet = ["// run `npm run x", "// -- --flag` first."].join("\n")
    expect(proseDashLines("a.ts", quiet)).toEqual([])
  })
  it("does not join // comments separated by a blank line or by code", () => {
    expect(proseDashLines("a.ts", "// a `b\n\n// c -- d`")).toEqual([3])
    expect(proseDashLines("a.ts", "// a `b\nx()\n// c -- d`")).toEqual([3])
  })
  it("does not join a // comment to a block comment on the next line", () => {
    expect(proseDashLines("a.ts", "/* a `b */\n// c -- d`")).toEqual([2])
    expect(proseDashLines("a.ts", "// a `b\n/* c -- d` */")).toEqual([2])
  })
})
