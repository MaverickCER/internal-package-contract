// Reuses a mutation run when nothing that could change its result has changed.
//
// A mutation run is a function of the code, the tests, the configuration and the tools that run them. When a
// pass was recorded for exactly the same inputs, running it again can only say the same thing an hour later. This
// records the evidence of a run against a hash of every input, and hands that evidence back, unchanged, when the
// hash is the same. It never decides anything: the check still reads the evidence and applies its own policy, so a
// reused run is judged exactly like a fresh one.
//
// What it does not see: files git ignores that are not derived from the ones it does, and the installed packages
// beyond what the lockfile pins. Neither is ordinary for a package that builds from tracked sources, and CI, which
// starts from a clean checkout, never reuses anything.

import { createHash } from "node:crypto"
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import path from "node:path"

import { filesOf } from "../checkout-files.mjs"

/** Where the evidence of a run, and the record of which inputs it was for, live. */
export const MEMO_DIRECTORY = "reports/mutation"
/** Raise this when what is hashed changes, so an older record is never mistaken for a current one. */
const FORMAT = "1"
/** Generated by the tools themselves, so never an input to them. */
const GENERATED = ["reports", "coverage", ".stryker-tmp", "node_modules"]

/**
 * @param {string} cwd - the package.
 * @param {string} [node] - the Node.js version, which is an input too.
 * @returns {string} a hash of every file git does not ignore (named and by content), and of the Node.js version.
 */
export function inputsHash(cwd, node = process.version) {
  const hash = createHash("sha256").update(`${FORMAT}\0${node}\0`)
  const present = filesOf(cwd)
    .filter((file) => !GENERATED.includes(String(file.split(/[\\/]/, 1))))
    .filter((file) => existsSync(path.join(cwd, file)))
  // Stryker disable next-line MethodExpression: equivalent -- git lists files in order already, and sorting only makes a listing made without git stable, which a filesystem that happens to list alphabetically cannot show.
  const files = present.sort()
  for (const file of files) {
    hash.update(`${file}\0`).update(
      createHash("sha256")
        .update(readFileSync(path.join(cwd, file)))
        .digest(),
    )
  }
  return hash.digest("hex")
}

/** @param {string} cwd @returns {string} the file naming the inputs the kept evidence is for. */
const recordOf = (cwd) => path.join(cwd, MEMO_DIRECTORY, "memo.json")
/** @param {string} cwd @param {string} hash @returns {string} where the evidence for those inputs is kept. */
const keptAs = (cwd, hash) => path.join(cwd, MEMO_DIRECTORY, `memo-${hash}.json`)
/** @param {string} cwd @returns {string} the evidence the check reads. */
const evidenceOf = (cwd) => path.join(cwd, MEMO_DIRECTORY, "mutation.json")

/**
 * @param {string} cwd - the package.
 * @param {string} hash - {@link inputsHash} of it now.
 * @param {Record<string, string | undefined>} env - the process environment.
 * @returns {boolean} whether the evidence for these exact inputs was kept, and was put back for the check to read.
 *   Never under CI, and never when `IPC_MUTATION_MEMO=0`.
 */
export function recall(cwd, hash, env) {
  if (env.CI !== undefined && env.CI !== "" && env.CI !== "false") return false
  if (env.IPC_MUTATION_MEMO === "0") return false
  /** @type {{ hash?: unknown }} */
  let kept
  try {
    kept = JSON.parse(readFileSync(recordOf(cwd)).toString())
  } catch {
    // Nothing was kept, or what was kept cannot be read.
    return false
  }
  if (kept.hash !== hash || !existsSync(keptAs(cwd, hash))) return false
  copyFileSync(keptAs(cwd, hash), evidenceOf(cwd))
  return true
}

/** What a mutant may have ended as in a run worth keeping: caught, or not a mutant of the code at all. */
const CLEAN = new Set(["Killed", "Ignored", "RuntimeError", "CompileError"])

/**
 * @param {string} file - the evidence of a run.
 * @returns {boolean} whether every mutant in it was caught or left out. A run in which any mutant survived, had no
 *   test, or timed out is never kept: it may be a loaded machine's result, and replaying it would pin that.
 */
// Stryker disable BlockStatement: equivalent -- an empty handler returns undefined, which `remember` reads as not clean.
function isClean(file) {
  try {
    /** @type {{ files?: Record<string, { mutants?: { status?: unknown }[] }> }} */
    const report = JSON.parse(readFileSync(file).toString())
    // Stryker disable next-line ArrayDeclaration: equivalent -- a placeholder entry has a status no run can end with, so the run is not kept either way.
    const mutants = Object.values(report.files ?? {}).flatMap((entry) => entry.mutants ?? [])
    return mutants.length > 0 && mutants.every((mutant) => CLEAN.has(String(mutant.status)))
  } catch {
    // Not there, or not a report: nothing to vouch for.
    return false
  }
}
// Stryker restore BlockStatement

/**
 * Keeps the evidence of a run that finished, for the inputs it ran on, and forgets older ones.
 * @param {string} cwd - the package.
 * @param {string} hash - {@link inputsHash} of it before the run.
 * @param {number | null} status - how the run exited; only a clean exit is kept, and only when every mutant in the
 *   evidence was caught or left out.
 */
export function remember(cwd, hash, status) {
  if (status !== 0 || !existsSync(evidenceOf(cwd)) || !isClean(evidenceOf(cwd))) return
  const directory = path.join(cwd, MEMO_DIRECTORY)
  mkdirSync(directory, { recursive: true })
  for (const name of readdirSync(directory)) {
    if (name.startsWith("memo-")) rmSync(path.join(directory, name))
  }
  copyFileSync(evidenceOf(cwd), keptAs(cwd, hash))
  writeFileSync(recordOf(cwd), `${JSON.stringify({ hash })}\n`)
}
