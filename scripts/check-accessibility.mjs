// Entry point for the `Accessibility` check (see checks/accessibility.ts). Runs pa11y over the built docs
// site in the working directory and prints one JSON envelope: `{ ok: true, value, pagesScanned, ... }`
// or `{ ok: false, error }`. The policy decides the verdict; a finding never makes this exit non-zero.
//
// What is read: the pages scripts/accessibility-pages.mjs resolves under docs/, each loaded over a
// file:// URL in a headless Chrome. Two runners judge each page, axe-core and HTML_CodeSniffer, because
// each finds problems the other does not. The pages are committed HTML, so nothing is built first.
//
// Where Chrome comes from: package.json `overrides` aliases pa11y's `puppeteer` to `puppeteer-core`, so
// no browser is downloaded and no install script runs (a supply-chain scanner flags install scripts).
// A browser must already be on the machine: `PUPPETEER_EXECUTABLE_PATH` or `CHROME_PATH` when set, else
// the usual install locations for the platform, else a PATH lookup of the common binary names. None
// found is `{ ok: false }` with the error the policy records as the `Accessibility:no-chrome`
// degradation. Chrome runs with its sandbox off because a CI runner restricts the kernel feature the
// sandbox needs; every page it loads is the package's own committed HTML.
//
// Counted in the envelope and never failed on: axe results axe itself marks as needing manual review,
// the nested-interactive result axe raises on TypeDoc's generated navigation tree, and HTML_CodeSniffer's
// duplicate-id report on an id named like an `Object.prototype` member. `pagesScanned` lets the policy
// tell a clean scan from a site that was not there to scan.

import pa11y from "pa11y"
import { sync as spawnSync } from "cross-spawn"
import { access } from "node:fs/promises"
import { join, relative } from "node:path"
import { pathToFileURL } from "node:url"
import { resolvePages } from "./accessibility-pages.mjs"

const repoRoot = process.cwd()
const docsDir = join(repoRoot, "docs")

// Every well-known system Chrome/Chromium install location this check knows to look for, in
// priority order, per platform -- checked only if `PUPPETEER_EXECUTABLE_PATH`/`CHROME_PATH`
// (an explicit override) isn't already set. Covers GitHub Actions' own `ubuntu-latest` runner
// image (ships Google Chrome preinstalled) and the common macOS/Linux developer-machine defaults.
const CANDIDATE_EXECUTABLE_PATHS = {
  darwin: [
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Chromium.app/Contents/MacOS/Chromium",
  ],
  linux: [
    "/usr/bin/google-chrome-stable",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium-browser",
    "/usr/bin/chromium",
  ],
  win32: [
    "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
    "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
  ],
}

// A last-resort PATH lookup for a handful of common binary names -- covers a Chromium installed
// under a name/location this check's own candidate list doesn't happen to enumerate.
const PATH_LOOKUP_NAMES = ["google-chrome-stable", "google-chrome", "chromium-browser", "chromium"]

async function pathExists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

/**
 * Finds a real, usable Chrome/Chromium executable on this machine -- `puppeteer-core` (see this
 * module's own doc comment for why it's used in place of real `puppeteer`) bundles no browser of
 * its own and requires one to be supplied explicitly.
 * @returns The executable's absolute path, or `undefined` if none could be found.
 */
async function findChromeExecutable() {
  const override = process.env.PUPPETEER_EXECUTABLE_PATH ?? process.env.CHROME_PATH
  if (override && (await pathExists(override))) return override

  const candidates = CANDIDATE_EXECUTABLE_PATHS[process.platform] ?? []
  for (const candidate of candidates) {
    if (await pathExists(candidate)) return candidate
  }

  for (const name of PATH_LOOKUP_NAMES) {
    const which = spawnSync(process.platform === "win32" ? "where" : "which", [name], {
      encoding: "utf8",
    })
    const found = which.stdout?.split("\n")[0]?.trim()
    if (which.status === 0 && found) return found
  }

  return undefined
}

/** An axe result axe itself could not decide (its `incomplete` bucket). */
function isNeedsReview(issue) {
  return issue.runner === "axe" && issue.runnerExtras?.needsFurtherReview === true
}

/**
 * TypeDoc's own navigation tree puts each module's link inside its disclosure `<summary>`, which axe
 * reports as nested-interactive. The markup is generated by TypeDoc's bundled script (the link is the
 * entry's label, so it cannot be removed without breaking navigation); it is an upstream defect and is
 * counted rather than failed on. The same violation anywhere else in a page still fails.
 */
function isTypedocNavNestedInteractive(issue) {
  return (
    issue.runner === "axe" &&
    issue.code === "nested-interactive" &&
    /^#tsd-nav-container\b/.test(issue.selector ?? "")
  )
}

/**
 * HTML_CodeSniffer's duplicate-id rule (F77) tracks ids in a plain object, so an element whose id is the
 * name of an `Object.prototype` member -- TypeDoc's `#constructor` section -- is reported as a duplicate of
 * itself. Verified by hand: the document has exactly one such id. Counted, not failed on.
 */
function isHtmlcsPrototypeIdFalsePositive(issue) {
  return (
    issue.runner === "htmlcs" &&
    /F77$/.test(issue.code ?? "") &&
    /Duplicate id attribute value "(constructor|__proto__|toString|valueOf|hasOwnProperty|isPrototypeOf|propertyIsEnumerable|toLocaleString)"/.test(
      issue.message ?? "",
    )
  )
}

try {
  const executablePath = await findChromeExecutable()
  if (executablePath === undefined) {
    process.stdout.write(
      JSON.stringify({
        ok: false,
        error:
          "no system Chrome/Chromium executable found. Install one, or set PUPPETEER_EXECUTABLE_PATH.",
      }),
    )
    process.exitCode = 0
  } else {
    const chromeLaunchConfig = {
      executablePath,
      // Chromium's own sandbox needs kernel unprivileged-user-namespace support, which a GitHub
      // Actions runner's AppArmor profile restricts -- without these flags Chrome exits
      // immediately on launch and pa11y produces no report at all. Safe here: every page this
      // check ever loads is the consumer's own static, committed HTML over a file:// URL, never
      // untrusted content.
      args: ["--no-sandbox", "--disable-setuid-sandbox"],
    }

    const existingPages = await resolvePages(docsDir)

    const perPage = await Promise.all(
      existingPages.map(async (path) => {
        const result = await pa11y(pathToFileURL(path).href, {
          chromeLaunchConfig,
          runners: ["axe", "htmlcs"],
        })
        // Attach the repo-relative page path to every issue -- with more than one page scanned,
        // a finding's rationale has to say which page it is on to be actionable.
        const page = relative(repoRoot, path)
        return result.issues.map((issue) => ({ ...issue, page }))
      }),
    )

    // `pagesScanned` lets the policy tell a genuine "0 issues across N pages" pass apart from
    // "0 pages existed to scan" (no built docs site at all) -- both produce an empty `value`
    // array otherwise, and only the first is actually a clean pass. See resolvePages() above.
    // axe marks a result `needsFurtherReview` when it cannot decide (typically a text colour whose background it
    // cannot read: text inside an `<svg>`, or partly covered by a sticky element). pa11y reports those as errors.
    // They are set aside and counted instead -- by axe's own definition they are not failures -- while every
    // decided violation still fails. The colour pairs the benchmark charts use are checked numerically by this
    // package's own tests (benchmark-render-page.test.ts).
    const all = perPage.flat()
    const needsReview = all.filter(isNeedsReview)
    const upstream = all.filter(isTypedocNavNestedInteractive)
    const htmlcsBug = all.filter(isHtmlcsPrototypeIdFalsePositive)
    process.stdout.write(
      JSON.stringify({
        ok: true,
        value: all.filter(
          (issue) =>
            !isNeedsReview(issue) &&
            !isTypedocNavNestedInteractive(issue) &&
            !isHtmlcsPrototypeIdFalsePositive(issue),
        ),
        needsReview: needsReview.length,
        typedocNavNestedInteractive: upstream.length,
        htmlcsPrototypeIdFalsePositives: htmlcsBug.length,
        pagesScanned: existingPages.length,
      }),
    )
    process.exitCode = 0
  }
} catch (error) {
  process.stdout.write(
    JSON.stringify({
      ok: false,
      error: error instanceof Error ? error.message : String(error),
    }),
  )
  process.exitCode = 1
}
